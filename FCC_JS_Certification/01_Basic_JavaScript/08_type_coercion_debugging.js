// Тема: Лабораторна робота - Налагодження перетворення типів (Type Coercion)
// Правило архітектури: Ніколи не покладайся на неявне перетворення типів. Булеві значення, рядки та null не повинні брати участь у математичних операціях.

// 1. Звичайне додавання
let firstResult = 5 + 10;

// 2. Звичайне віднімання
let secondResult = 8 - 5;

// 3. Заміна булевого значення (скоріш за все, тут було 5 + true) на чисте число
let thirdResult = 5 + 1;

// 4. Заміна булевого значення (тут, ймовірно, було 8 + false) на чисте число
let fourthResult = 8 + 0;

// 5. Заміна рядка (було "10" * 2) на чисте число
let fifthResult = 10 * 2;

// 6. Заміна null (було 22 + null) на чисте число
let sixthResult = 22 + 0;

// Вивід для перевірки
console.log(
  firstResult,
  secondResult,
  thirdResult,
  fourthResult,
  fifthResult,
  sixthResult,
);
