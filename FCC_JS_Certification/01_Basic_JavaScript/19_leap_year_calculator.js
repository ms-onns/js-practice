// Тема: Лабораторна робота - Калькулятор високосного року
// Використання оператора modulo (%) та складних логічних умов (&&, ||)

// 1. Оголошуємо змінну year поза межами функції (вимога тестів)
const year = 2024;

// 2. Створюємо функцію для перевірки
function isLeapYear(yearParam) {
  // Професійний підхід: об'єднуємо умови в один чистий if/else.
  // Рік є високосним, ЯКЩО:
  // (він ділиться на 4 І НЕ ділиться на 100) АБО (він ділиться на 400)
  if ((yearParam % 4 === 0 && yearParam % 100 !== 0) || yearParam % 400 === 0) {
    // Використовуємо шаблонні рядки для правильного форматування виводу
    return `${yearParam} is a leap year.`;
  } else {
    return `${yearParam} is not a leap year.`;
  }
}

// 3. Викликаємо функцію і зберігаємо результат у змінну result
const result = isLeapYear(year);

// 4. Виводимо результат у консоль
console.log(result);

